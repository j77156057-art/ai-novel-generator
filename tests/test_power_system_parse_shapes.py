def test_细分型_标题加正文加小境界列表():
    systems = parse_systems(FINE)
    assert len(systems) == 1, systems
    s = systems[0]
    assert s["类型"] == "细分型", s["类型"]
    assert [r["名称"] for r in s["境界"]] == ["开脉境", "炼气境", "筑基境"]
    # 小境界来自正文里的列表
    stages = [x["名称"] for x in s["境界"][0]["小境界"]]
    assert stages and "九重大圆满" in stages, stages
    # 说明来自标题下的正文
    assert "九条主脉" in s["境界"][0]["说明"], s["境界"][0]["说明"]
    assert bands_of(s), "派生档位不能为空"


def test_序列型_不被正文里的短章节标题带偏():
    """正文有 3 个短章节标题，但真正的阶梯是 22 行的表（这里节选 4 行）。"""
    systems = parse_systems(SEQ)
    s = systems[0]
    assert s["类型"] == "序列型", s["类型"]
    assert [r["名称"] for r in s["境界"]] == ["守灯人", "拾忘者", "缝影人", "叩门者"]
    # 表格里没有「说明」列 ⇒ 用其余列拼
    assert s["境界"][0].get("说明"), s["境界"][0]
    assert not any(r.get("小境界") for r in s["境界"]), "序列型不该有小境界"


def test_粗放型_不被正文里的子表劫持():
    """真境界是 4 个 `##` 标题；子表是「修行者」的三小阶，不是境界。"""
    systems = parse_systems(SOFT)
    s = systems[0]
    assert s["类型"] == "粗放型", s["类型"]
    assert [r["名称"] for r in s["境界"]] == ["凡人", "修行者", "圣人", "神明"]
    assert "下" not in [r["名称"] for r in s["境界"]], "抓到子表了"


def test_章节标题不会被当成境界():
    """「五、为什么不能假设等差」不是境界。"""
    systems = parse_systems(SOFT)
    names = [r["名称"] for r in systems[0]["境界"]]
    assert not any("为什么" in n for n in names), names


def test_体系名不被书名号切坏():
    assert parse_systems(SOFT)[0]["名称"] == "四境：在、借、有、是"
    assert parse_systems(SEQ)[0]["名称"] == "缄默名录"
    assert parse_systems(FINE)[0]["名称"] == "九境九重制"


def test_细分型_有序列表形态():
    """第二轮真机：模型回的是 `1. **炼气境**` + 缩进列表，没有标题也没有表。"""
    systems = parse_systems(LIST_SHAPE)
    assert len(systems) == 1, systems
    s = systems[0]
    assert s["类型"] == "细分型", s["类型"]
    assert [r["名称"] for r in s["境界"]] == ["炼气境", "筑基境", "金丹境"]
    stages = [x["名称"] for x in s["境界"][0]["小境界"]]
    assert "九重大圆满" in stages, stages
    assert s["名称"] == "九境九重法", s["名称"]


def test_正文里的长句子列表不算小境界():
    """粗放型那篇的正文列表是要点（「怕弓弩、毒、围杀」），不是小境界。

    判据：小境界名字里必须带层级词（重/层/期/阶/品/级/段/第），且要短。
    """
    systems = parse_systems(SOFT)
    for r in systems[0]["境界"]:
        for st in (r.get("小境界") or []):
            assert any(h in st["名称"] for h in
                       ("重", "层", "期", "阶", "品", "级", "段", "第")), st
