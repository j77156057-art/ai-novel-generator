"""体系解析要认得住真实模型的三种形态（2026-10-29 真机验证发现）。

## 真机结果：第一版三类里只有一类正确

| 案例 | 模型回的形态 | 第一版结果 |
|---|---|---|
| 细分型 | `#### 1. 开脉境` 标题 + 正文 + 小境界列表 | **解析不出体系** |
| 序列型 | 表格（22 行） | 对，22 境 |
| 粗放型 | `## 一、凡人（在）` 标题 + 正文，正文里还嵌一张 3 行子表 | **抓错表**：境界变成 下/中/上 |

两处根因：

1. **只认表格和 JSON** —— 模型最常回的「标题 + 正文」完全不认；
2. **表格解析会抓到文档里的子表** —— 真境界是四个 `##` 标题，
   而「修行者」小节里那张 `| 阶 | 名 | 实际战力 | 弱点 |` 被当成了境界表。

## 修法

- `_parse_systems_from_headings`：按标题层级还原 —— 哪一层能凑出 ≥3 个
  「像境界」的短标题就用哪一层；标题下正文当说明，正文里的列表当小境界。
- **两条路都跑，谁给出的境界更多就用谁**（相同则标题优先）。
  只写「标题优先」会在序列型那篇选错（3 个章节标题 vs 22 行表）。
- 表格认不出「说明」列时，把没被用作名称/档位的其它列拼成说明。
- 有小境界 ⇒ 类型推断为**细分型**（否则默认序列型会把小境界抹掉）。

下面是三份真机原文的**节选**（保留结构与表头，删掉重复行）。
"""
