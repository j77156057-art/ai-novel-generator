"""**心理描写**的补齐：让生成文本里真的有人物内心。

## 缺口（实测，2026-10-29，发布版冒烟库）

用五层判据量「心理描写密度」（处/千字）：

| 判据 | 生成文本 | 参考书语料 | 倍数 |
|---|---|---|---|
| L1 显式心理动词（想起/心里/暗自/犹豫/后悔…） | **4 处** | 200 处 | **缺 50×** |
| L2 动词化心理（明白过来/意识到/忽然觉得/以为…） | **7 处** | 304 处 | **缺 43×** |
| L3 判断句式 | 3 处 | 5 处 | 持平 |
| L4 括号独白 | 0 | 0 | 持平 |
| L5 代词+心理容器（心头/心底/胸中） | 1 处 | 5 处 | 持平 |

⇒ 心理描写**不是「少」，是几乎没有**。
（同一批量测里，**场景描写反而超标**：环境词 19.3/千字 vs 参考书 12.7/千字；
但含环境的行里 282 条同时带动作、只有 81 条是纯环境
⇒ 场景描写被「挂在动作后面」，没有独立成段。）

## 真书怎么写（从参考书原文归纳）

    赵北山**心中轻轻叹息**，黄小满若能稍稍聪慧一些……
    老道士闻言…**心中咂舌**，这小家伙何止是天生神力
    赵长安**想着方才**被一群拿木矛柴刀追着打的悲壮光景，**强忍揍人的念头**
    白小满**心中哀叹**，又要有无数良民被一个荒诞的缘由遭劫了吗？
    起先她**以为是自己胆小**，但越长大，胆子越大……

**三个可复用的模式**：

1. **心理动词 + 人物 + 内容**（「心中轻轻叹息」「犹豫了一下」）
2. **判断动词 + 从句**（「以为是自己胆小」「觉得那眼神偏了半分」）
3. **心理活动 + 外化动作**（「强忍揍人的念头」「把念头压了回去」）

## 为什么不能只靠提示词说「要写心理」

实测教训（同项目）：提示词里写「不要情绪直陈」「用动作承载情绪」
⇒ 生成文本里**心理描写几乎绝迹**（4 处 / 6 万字）。

因为「用动作承载情绪」与「写心理」在模型眼里是**互斥**的，
而模型的默认倾向是把一切情绪都转成动作/神态（实测外貌 25.3/千字 vs 参考书 13.1，
动作 22.3 vs 8.6 ⇒ **全是动作**）。

⇒ 必须给**可判定的目标**（像声纹那样），并且**可机检**。
"""

from __future__ import annotations

import re
from typing import Any

#: 心理动词（第一类：显式）。
#:
#: 词表来自**参考书实测**（北荒刀歌语料里高频出现的心理动词），
#: 不是凭印象列的 —— 列进来的是真书里真出现过的。
PSYCH_VERBS: tuple[str, ...] = (
    "想起", "想着", "回想", "记起", "回想",
    "心里", "心中", "心头", "心底", "胸中", "腹中",
    "暗自", "暗想", "暗地", "暗自",
    "犹豫", "迟疑", "踌躇",
    "后悔", "不甘", "庆幸", "窃喜",
    "算计", "盘算", "权衡", "掂量",
    "哀叹", "叹息", "咂舌", "苦笑", "冷笑",
    "明白", "意识到", "醒过味来", "省得", "明白过来",
    "觉得", "以为", "怀疑", "猜想",
    "担心", "害怕", "恐惧", "惊慌", "不安", "焦急",
    "恼火", "生气", "怨恨", "委屈",
    "懂得", "知道", "明白",
)

#: 心理动词的**动作化变体**（模型更爱用的说法：把心理写成动作）。
#:
#: 实测：生成文本里「沈砚眨了下眼，把这念头压了回去」——这是心理的**外化**，
#: 但「念头」这个词本身仍是心理信号 ⇒ 值得认。
PSYCH_OUTER: tuple[str, ...] = (
    "念头", "心思", "想法", "主意", "念头一转",
    "下定决心", "打定主意", "拿定主意",
    "忍住", "强忍", "压下", "按下", "收住", "咽下",
)

#: 「判断动词 + 从句」型（第二类）。
#:
#: 真书：「起先她**以为是自己胆小**」「只觉得那眼神偏了，偏了半分」
#: ⇒ 关键特征：**主语 + 判断动词 + 「是/像/在…」**。
PSYCH_JUDGE = re.compile(
    r"(?:他|她|他们|她们|[\u4e00-\u9fff]{2,3})"
    r"(?:心里|心中|心头|心底)?"
    r"(以为|觉得|觉得|好像|似乎|仿佛|像是|算是|当作|不当)"
)

#: 心理描写**整体**的可检信号（用于机检与密度量）。
PSYCH_PATTERN = re.compile(
    "|".join(
        re.escape(v) for v in (PSYCH_VERBS + PSYCH_OUTER)
    ) + r"|" + PSYCH_JUDGE.pattern
)

#: 场景描写的可检信号（环境 + 无动作 ⇒ 独立场景段）。
#:
#: 实测：生成文本里含环境的行有 282 条同时带动作、只有 81 条纯环境
#: ⇒ 场景描写被「挂在动作后面」。这一项单独度量，不与心理混。
SCENE_ONLY_PATTERN = re.compile(
    r"(夜色|天色|晨光|日光|月光|阳光|灯火|光|风|雨|雪|雾|潮|湿|冷|暖|"
    r"寂静|安静|声音|气味|味道|腥|臭|空气|黑暗|漆黑|昏|光线)"
)


def count_psych(text: str) -> int:
    """数一段文本里的心理描写处数。"""
    if not text:
        return 0
    return len(PSYCH_PATTERN.findall(text))


def psych_density(texts: list[str]) -> float:
    """心理描写密度（处/千字）。"""
    joined = "\n".join(t or "" for t in texts)
    n = len(joined)
    if not n:
        return 0.0
    return count_psych(joined) * 1000.0 / n


def has_psych(text: str) -> bool:
    """这一段有没有心理描写？"""
    return count_psych(text) > 0


def scene_only_lines(text: str) -> list[str]:
    """只含环境、不含动作的行（独立场景段的候选）。

    用来量「场景描写有没有独立成段」—— 实测生成文本里这类行只有 81 条，
    而含环境的行共 363 条 ⇒ 场景多被挂在动作后面。
    """
    from app.style.beat_insert import _is_action_only_line  # 复用既有判定

    out: list[str] = []
    for line in (text or "").split("\n"):
        s = line.strip()
        if len(s) < 12:
            continue
        if not SCENE_ONLY_PATTERN.search(s):
            continue
        if _is_action_only_line(s):
            continue
        out.append(s)
    return out


# ==================================================================== #
# 提示词侧：给模型一个**可判定**的目标，而不是「要写心理」
# ==================================================================== #

#: 心理描写的**模式清单**（进提示词）。
#:
#: 每个模式都带**真书原句**作范例 ⇒ 模型照着模式写，而不是凭空想象「心理描写」。
PSYCH_PATTERNS: tuple[tuple[str, str], ...] = (
    ("心中直陈",
     "「心中轻轻叹息」「心里一沉」「心头一紧」——心理动词直接带情绪，"
     "后面接一句具体内容"),
    ("判断句",
     "「以为是自己胆小」「只觉得那眼神偏了半分」「觉得不对劲」"
     "——主语 + 判断动词 + 从句，写出他**怎么想**"),
    ("回忆闪回",
     "「想着方才被追着打的悲壮光景」「记起父亲说过的话」"
     "——一句回忆插进当下，推动他的决定"),
    ("外化动作",
     "「强忍揍人的念头」「把这念头压了回去」「按下火气」"
     "——心理写成身体动作，但**保留心理的那个词**"),
    ("权衡算计",
     "「盘算着这趟能不能全身而退」「心里比较着两条路的轻重」"
     "——写他在做选择，而不是只写他做了什么"),
)

#: 场景描写的模式清单（进提示词）。
SCENE_PATTERNS: tuple[tuple[str, str], ...] = (
    ("独立成段",
     "一段只写空间、光线、声音、气味，**不挂任何人的动作**"
     "（让读者先站进那个地方，再看人）"),
    ("感官分层",
     "一样写夜：先写声音（更漏四下），再写光（灯芯暗了半分），"
     "最后写气味（药味压住了血腥）"),
    ("以物写境",
     "用一个具体物件交代环境：半张脸垂着的泥胎供桌、"
     "被刀刮去旧文的石槽"),
    ("天气参与情节",
     "雾让谁看不清谁、雨让谁没法赶路——环境要**起作用**，不是背景板"),
)


def render_psych_guide() -> str:
    """渲染心理描写指引（进 system 提示）。"""
    lines = ["【心理描写】"]
    for name, demo in PSYCH_PATTERNS:
        lines.append(f"- {name}：{demo}")
    # 频次对齐参考书（实测 3.06 处/千字）。
    # ⚠️ 不能写「每段至少一处」：A/B 实测那样会写到 9.73 处/千字
    # （参考书的 3.2 倍），读起来像内心独白堆砌。
    lines.append("- 频次：**每 2~3 段出现一处**即可（参考作者约三十分之一段）；"
                 "一段之内**不要连写好几处** —— 内心写多了就成独白，"
                 "读者会觉得啰嗦。")
    return "\n".join(lines)


def render_scene_guide() -> str:
    """渲染场景描写指引（进 system 提示）。"""
    lines = ["【场景描写】"]
    for name, demo in SCENE_PATTERNS:
        lines.append(f"- {name}：{demo}")
    lines.append("- 频次：场景转换或重要时刻，单独给一段只写环境，"
                 "别把环境全挂在动作后面。")
    return "\n".join(lines)
